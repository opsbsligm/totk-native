def main():
    assets=ROOT/'assets/controller'; assets.mkdir(parents=True, exist_ok=True)
    header=ROOT/'src/gfx/totk_deck_bitmaps.h'
    old=header.read_text()
    tail=old[old.index('static inline int nd_deck_source_view'):]
    result=['/* Original vector Deck artwork generated by tools/draw_deck_art.py. */',
            '/* Coordinates preserve existing game-layout callout anchors. */',
            '#ifndef ND_TOTK_DECK_BITMAPS_H', '#define ND_TOTK_DECK_BITMAPS_H',
            '#include <stdint.h>', '#include <stddef.h>', '#include <string.h>',
            'enum { ND_DECK_W=580, ND_DECK_H=340, ND_DECK_BYTES=788800 };',
            'typedef struct { uint16_t n; uint8_t grey, alpha; } nd_deck_run;']
    for view,transform in (('front','translate(2 26)'),('inclined','matrix(.96 0 0 .75 13 72)')):
        shoulder=''
        if view=='inclined':
            shoulder='''<g fill="#202020" stroke="#9d9d9d"><rect x="27" y="35" width="62" height="30" rx="10"/><rect x="491" y="35" width="62" height="30" rx="10"/></g>
            <g font-family="sans-serif" font-size="11" fill="#dedede" text-anchor="middle"><text x="58" y="54">L2</text><text x="522" y="54">R2</text></g>'''
        svg=f'<svg xmlns="http://www.w3.org/2000/svg" width="580" height="340" viewBox="0 0 580 340">{shoulder}<g transform="{transform}">{front()}</g></svg>'
        (assets/(view+'.svg')).write_text(svg+'\n')
        png=cairosvg.svg2png(bytestring=svg.encode(),output_width=1160,output_height=680)
        image=Image.open(io.BytesIO(png)).convert('RGBA').resize((580,340),Image.Resampling.LANCZOS)
        # RLE stores greyscale and alpha, preserving antialiased transparency.
        raw=image.tobytes(); runs=[]
        for i in range(0,len(raw),4):
            r,g,b,a=raw[i:i+4]
            if r!=g or g!=b: raise ValueError('Art must be greyscale')
            if a==0: g=0
            if runs and runs[-1][1:]==(g,a) and runs[-1][0]<65535:
                runs[-1]=(runs[-1][0]+1,g,a)
            else: runs.append((1,g,a))
        result.append('static const nd_deck_run nd_deck_'+view+'[] = {')
        result.extend(''.join('{%d,%d,%d},'%run for run in runs[i:i+12]) for i in range(0,len(runs),12)); result.append('};')
        image.save(assets/(view+'.png'))
    result.append(tail)
    header.write_text('\n'.join(result))
    print('Authored SVG, preview PNG and runtime header regenerated')


if __name__=='__main__': main()
